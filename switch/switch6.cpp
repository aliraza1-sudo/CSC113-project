#include<iostream>
using namespace std;
int main()
{
	int x;
	cout<<"Enter a day number (1-7)"<<endl;
	cin>> x;
	switch(x)
	{
		case 1:
			case 2:
				case 3:
					case 4:
						case 5:
							cout<<"Weekday"<<endl;
							break;
							case 6:
								case7:
									cout<<"Weekend"<<endl;
									break;
									default:
										cout<<"invalid input"<<endl;
	}
	return 0;
}
